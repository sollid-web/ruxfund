-- Fresh PostgreSQL schema for Ruxfund.
-- Run this in the Supabase SQL Editor. It creates tables and baseline
-- configuration only; it does not migrate existing users or transactions.

CREATE TABLE IF NOT EXISTS site (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL DEFAULT 'Ruxfund',
    site_url varchar(255) NOT NULL DEFAULT 'http://127.0.0.1:8000',
    url_name varchar(150) NOT NULL DEFAULT 'Ruxfund',
    email varchar(255) NOT NULL DEFAULT 'admin@example.com',
    admin varchar(255) NOT NULL DEFAULT 'admin@example.com',
    address varchar(255) NOT NULL DEFAULT '',
    phone varchar(80) NOT NULL DEFAULT '',
    image_link varchar(255) NOT NULL DEFAULT '',
    reg varchar(255) NOT NULL DEFAULT '',
    btc numeric(20, 8) NOT NULL DEFAULT 0,
    dep numeric(12, 2) NOT NULL DEFAULT 0,
    withdraw numeric(12, 2) NOT NULL DEFAULT 0,
    min_with numeric(12, 2) NOT NULL DEFAULT 10,
    max_with numeric(12, 2) NOT NULL DEFAULT 1000000,
    cardfee numeric(12, 2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(100) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    country varchar(100) NOT NULL DEFAULT 'Not Available',
    time bigint NOT NULL DEFAULT 0,
    active smallint NOT NULL DEFAULT 1,
    transfer smallint NOT NULL DEFAULT 0,
    "2fa" smallint NOT NULL DEFAULT 0,
    max numeric(12, 2) NOT NULL DEFAULT 0,
    msg text,
    kyc smallint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS plan (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type smallint NOT NULL DEFAULT 1,
    name varchar(150) NOT NULL,
    percent numeric(12, 4) NOT NULL DEFAULT 0,
    ref numeric(12, 4) NOT NULL DEFAULT 0,
    min numeric(12, 2) NOT NULL DEFAULT 10,
    max numeric(12, 2) NOT NULL DEFAULT 1000000,
    num integer NOT NULL DEFAULT 1,
    calc integer NOT NULL DEFAULT 24
);

CREATE TABLE IF NOT EXISTS transaction (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender integer NOT NULL DEFAULT 0,
    receiver varchar(100) NOT NULL DEFAULT 'x',
    amount numeric(20, 8) NOT NULL DEFAULT 0,
    type varchar(50) NOT NULL DEFAULT '',
    plan integer,
    paidby varchar(50),
    coin varchar(20),
    status smallint DEFAULT 0,
    show_bonus smallint NOT NULL DEFAULT 1,
    time bigint NOT NULL DEFAULT 0,
    updated bigint NOT NULL DEFAULT 0,
    closed smallint NOT NULL DEFAULT 0,
    closetime bigint
);
CREATE INDEX IF NOT EXISTS transaction_sender_idx ON transaction (sender);
CREATE INDEX IF NOT EXISTS transaction_type_idx ON transaction (type);

CREATE TABLE IF NOT EXISTS referral (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user" varchar(100) NOT NULL,
    ref varchar(100) NOT NULL,
    time bigint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS referral_ref_idx ON referral (ref);

CREATE TABLE IF NOT EXISTS kyc (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL DEFAULT '',
    email varchar(255) NOT NULL DEFAULT '',
    phone varchar(80) NOT NULL DEFAULT '',
    address varchar(255) NOT NULL DEFAULT '',
    state varchar(100) NOT NULL DEFAULT '',
    country varchar(100) NOT NULL DEFAULT '',
    image varchar(255) NOT NULL DEFAULT '',
    userid integer NOT NULL DEFAULT 0,
    status smallint NOT NULL DEFAULT 0,
    time bigint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS kyc_userid_idx ON kyc (userid);

CREATE TABLE IF NOT EXISTS wallet (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user" integer NOT NULL DEFAULT 0,
    wallet varchar(255) NOT NULL DEFAULT '',
    type varchar(50) NOT NULL DEFAULT '',
    time bigint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS wallet_user_idx ON wallet ("user");

CREATE TABLE IF NOT EXISTS sitewallet (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type varchar(20) NOT NULL UNIQUE,
    address varchar(255) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS fak (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users integer NOT NULL DEFAULT 0,
    deposit numeric(20, 2) NOT NULL DEFAULT 0,
    withdraw numeric(20, 2) NOT NULL DEFAULT 0,
    days integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS faq (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question varchar(1000) NOT NULL,
    answer text NOT NULL
);

CREATE TABLE IF NOT EXISTS test (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL DEFAULT '',
    testimony text NOT NULL,
    image varchar(255) NOT NULL DEFAULT '1'
);

CREATE TABLE IF NOT EXISTS msg (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL DEFAULT '',
    subject varchar(255) NOT NULL DEFAULT '',
    email varchar(255) NOT NULL DEFAULT '',
    msg text NOT NULL
);

CREATE TABLE IF NOT EXISTS card (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender integer NOT NULL DEFAULT 0,
    type varchar(80) NOT NULL DEFAULT '',
    address varchar(255) NOT NULL DEFAULT '',
    status smallint NOT NULL DEFAULT 0,
    time bigint NOT NULL DEFAULT 0,
    name varchar(150) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS flow (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(100) NOT NULL DEFAULT 'admin',
    password varchar(255) NOT NULL DEFAULT '',
    code varchar(255) NOT NULL DEFAULT 'admin_code'
);

